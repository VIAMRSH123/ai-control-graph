"""FastAPI factory shared by the three apps.

Runs locally with uvicorn and on AWS Lambda through Mangum, from the same
source. That matters for evidence: the probe collector exercises exactly the
code that runs in production, rather than a local stand-in that might behave
differently.
"""

from __future__ import annotations

from typing import Any, Callable

from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse

from .core import ModelClient, RateLimiter, audit, run_inference, system_card


def build(
    *,
    key: str,
    name: str,
    purpose: str,
    risk_tier: str,
    oversight: str,
    limitations: list[str],
    system_prompt: str,
    route: str,
    input_field: str,
    needs_human_review: bool = False,
    max_tokens: int = 700,
    enrich: Callable[[str, Any], dict] | None = None,
    preprocess: Callable[[str], str] | None = None,
) -> FastAPI:
    app = FastAPI(title=name, version="1.0.0")
    limiter = RateLimiter()
    client = ModelClient()

    @app.get("/healthz")
    def healthz() -> dict:
        return {"status": "ok", "system": key}

    @app.get("/.well-known/ai-system-card.json")
    def card() -> dict:
        return system_card(key, name, purpose, risk_tier, oversight,
                           limitations, route=route, input_field=input_field)

    @app.post(route)
    async def handle(request: Request) -> JSONResponse:
        caller = request.client.host if request.client else "unknown"
        allowed, headers = limiter.check(caller)
        if not allowed:
            audit({"event": "rate_limited", "ai_system": key, "caller_hash": hash(caller)})
            return JSONResponse(
                {"error": "rate limit exceeded"}, status_code=429, headers=headers
            )

        try:
            body = await request.json()
        except Exception:  # noqa: BLE001
            return JSONResponse({"error": "expected a JSON body"}, status_code=400, headers=headers)

        text = (body or {}).get(input_field)
        if not isinstance(text, str) or not text.strip():
            return JSONResponse(
                {"error": f"'{input_field}' is required"}, status_code=400, headers=headers
            )

        # retrieval, redaction of protected attributes, or anything else an app
        # must do to the input before the model sees it
        prepared = preprocess(text) if preprocess else text

        try:
            answer, record = run_inference(
                key, system_prompt, prepared, client,
                human_review_required=needs_human_review, max_tokens=max_tokens,
            )
        except RuntimeError as exc:
            audit({"event": "inference_unavailable", "ai_system": key, "detail": str(exc)})
            return JSONResponse({"error": str(exc)}, status_code=503, headers=headers)

        payload: dict[str, Any] = {
            "request_id": record.request_id,
            "answer": answer,
            "ai_disclosure": f"This response was generated by an AI system ({name}).",
            "model_route": record.route,
            "human_review_required": record.human_review_required,
        }
        if enrich:
            payload.update(enrich(answer, record))
        return JSONResponse(payload, headers=headers)

    @app.post("/escalate")
    async def escalate(request: Request) -> dict:
        """Hand the interaction to a person.

        Article 14 human oversight requires that a person can take over, so the
        route exists and every use of it is logged.
        """
        body = await request.json()
        audit({
            "event": "human_escalation",
            "ai_system": key,
            "request_id": body.get("request_id"),
            "reason": body.get("reason", "unspecified"),
        })
        return {"status": "escalated", "queue": "human-review"}

    return app


def lambda_handler_for(app: FastAPI):
    """Adapt the app for Lambda, when Mangum is present.

    Returns None locally so that running with uvicorn needs no Lambda
    dependency. The same module therefore serves both, which is what lets the
    probe collector exercise production code rather than a local stand-in.
    """
    try:
        from mangum import Mangum
    except ImportError:
        return None
    return Mangum(app, lifespan="off")
